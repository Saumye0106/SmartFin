import sys
from pathlib import Path

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from statement_import import service
from statement_import.categorizer import categorize, extract_merchant
from statement_import.migrations import create_tables
from statement_import.parser import (StatementParseError, StatementPasswordRequired, parse_amount,
                                     parse_date, parse_statement)

FIXTURES = Path(__file__).parent / "fixtures" / "statements"
EXPECTED_COUNT, EXPECTED_DEBIT, EXPECTED_CREDIT = 19, 30310.10, 47112.40
PDF_PASSWORD = "SAUM0101"


def _read(name):
    return (FIXTURES / name).read_bytes()


# ── Parser ───────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("name,password", [
    ("hdfc_style.csv", None),            # preamble + footer summary
    ("sbi_style.xlsx", None),            # wrapped narrations across rows
    ("axis_style.csv", None),            # single amount column + Dr/Cr
    ("icici_style.pdf", None),           # multi-page, header repeated
    ("icici_style_protected.pdf", PDF_PASSWORD),
])
def test_parses_each_bank_layout_exactly(name, password):
    txns = parse_statement(name, _read(name), password)
    assert len(txns) == EXPECTED_COUNT
    assert round(sum(t.amount for t in txns if t.direction == "debit"), 2) == EXPECTED_DEBIT
    assert round(sum(t.amount for t in txns if t.direction == "credit"), 2) == EXPECTED_CREDIT
    assert txns[0].txn_date.isoformat() == "2026-09-01"
    assert txns[-1].balance == 35052.30
    assert all(t.amount > 0 for t in txns)


def test_wrapped_narration_is_rejoined():
    txns = parse_statement("sbi_style.xlsx", _read("sbi_style.xlsx"))
    assert any(t.description.startswith("NEFT CR-HDFC0000001-ACME") and "SALARY SEP 2026" in t.description for t in txns)


