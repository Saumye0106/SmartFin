def test_users_are_isolated(conn):
    rows = service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"]
    service.confirm(conn, 1, rows)
    p_other = service.preview(conn, 2, "hdfc_style.csv", _read("hdfc_style.csv"))
    assert p_other["summary"]["duplicate_count"] == 0  # user 1's import doesn't affect user 2


def test_correction_is_learned_for_next_import(conn):
    rows = service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"]
    for x in rows:
        if x["merchant"] == "Priya Sharma":
            x["category"] = "rent"
    assert service.confirm(conn, 1, rows)["rules_learned"] == 1
    service.undo_batch(conn, 1, conn.execute("SELECT import_batch_id FROM bank_transactions LIMIT 1").fetchone()[0])

    again = service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"]
    priya = next(x for x in again if x["merchant"] == "Priya Sharma")
    assert priya["category"] == "rent" and priya["category_source"] == "user_rule"


def test_excluded_rows_and_non_expense_categories(conn):
    rows = service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"]
    rows[1]["include"] = False                       # rent payment excluded
    rows[2]["category"] = "transfer"                 # mark a debit as self-transfer
    r = service.confirm(conn, 1, rows)
    assert r["excluded"] == 1 and r["imported"] == EXPECTED_COUNT - 1
    assert conn.execute("SELECT expense_id FROM bank_transactions WHERE category = 'transfer'").fetchone()[0] is None


def test_confirm_revalidates_client_rows(conn):
    rows = service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"]
    for bad in ({"category": "lottery"}, {"amount": -5}, {"direction": "sideways"}, {"date": "31/02/2026"}):
        tampered = [dict(rows[0], **bad)] + rows[1:]
        with pytest.raises(ValueError):
            service.confirm(conn, 1, tampered)
    assert conn.execute("SELECT COUNT(*) FROM bank_transactions").fetchone()[0] == 0


def test_undo_removes_batch_and_its_expenses(conn):
    r = service.confirm(conn, 1, service.preview(conn, 1, "hdfc_style.csv", _read("hdfc_style.csv"))["rows"])
    conn.execute("INSERT INTO expense_entries (id, user_id, expense_date, category, amount) VALUES ('m1', 1, '2026-09-03', 'food', 99)")
    u = service.undo_batch(conn, 1, r["batch_id"])
    assert u["transactions_removed"] == EXPECTED_COUNT and u["expenses_removed"] == r["expenses_created"]
    remaining = conn.execute("SELECT id FROM expense_entries").fetchall()
    assert [x[0] for x in remaining] == ["m1"]  # manual expense untouched
    assert service.undo_batch(conn, 2, r["batch_id"])["transactions_removed"] == 0  # other users can't undo
